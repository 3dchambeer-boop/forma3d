# Browser end-to-end (Playwright + Chromium): CMG welcome page and the website content manager (CMS) on the offline
# platform — live 3D model, language switch, draft/preview/publish, validation, maintenance mode, rollback.
import pathlib, shutil, tempfile
from playwright.sync_api import sync_playwright
REPO = pathlib.Path(__file__).resolve().parents[2]
HERE = pathlib.Path(tempfile.mkdtemp(prefix='forma-e2e-')); S = str(HERE) + '/'
shutil.copy(REPO / 'services/ai_3d_engine/browser/forma-offline.html', HERE / 'forma.html')
def btn(pg, name): pg.locator('button:visible', has_text=name).first.click()
with sync_playwright() as p:
    ctx = p.chromium.launch_persistent_context(S + 'profile', args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--allow-file-access-from-files'], viewport={'width': 1360, 'height': 900})
    pg = ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto((HERE / 'forma.html').as_uri())
    pg.wait_for_function("document.querySelector('.wl-caption') && /FormaCAD/.test(document.querySelector('.wl-caption').textContent)", timeout=120000); pg.wait_for_timeout(600)
    print('WELCOME h1:', pg.inner_text('.wl h1'), '| caption:', pg.inner_text('.wl-caption'), '| canvas:', pg.locator('.wl-stage canvas').count(), '| title:', pg.title())
    pg.screenshot(path=S + 'welcome_desktop.png')
    btn(pg, 'English'); pg.wait_for_timeout(500)
    print('EN:', pg.inner_text('.wl h1'), '| dir:', pg.get_attribute('#v-welcome', 'dir'), '| cta:', pg.inner_text('.wl-cta'))
    pg.screenshot(path=S + 'welcome_en.png')
    pg.set_viewport_size({'width': 390, 'height': 844}); pg.wait_for_timeout(400)
    print('mobile hscroll:', pg.evaluate('document.documentElement.scrollWidth>innerWidth')); pg.screenshot(path=S + 'welcome_mobile.png', full_page=True)
    pg.set_viewport_size({'width': 1360, 'height': 900})
    btn(pg, 'العربية'); pg.wait_for_timeout(300); pg.locator('.wl-cta').click(); pg.wait_for_timeout(500)
    print('CTA leads to:', pg.inner_text('#v-login h1'))
    pg.fill('#newName', 'المدير'); pg.locator('form', has=pg.locator('#newName')).locator('button[type=submit]').click(); pg.wait_for_timeout(1500)
    pg.evaluate("location.hash='admin'"); pg.wait_for_timeout(700)
    # validation
    pg.fill('#cms_headline_ar', 'من الفكرة إلى القطعة في يدك.'); pg.evaluate("document.getElementById('cms_accent').value='#ffcc00'")
    pg.fill('#cms_links', 'Instagram | https://instagram.com/cmg\nبريد | javascript:alert(1)')
    btn(pg, 'احفظ المسودة'); pg.wait_for_timeout(400)
    print('ERRORS:', pg.locator('.cms + ul li').all_inner_texts())
    pg.evaluate("document.getElementById('cms_accent').value='#1d4ed8'"); pg.fill('#cms_links', 'Instagram | https://instagram.com/cmg')
    btn(pg, 'معاينة'); pg.wait_for_timeout(1500)
    print('PREVIEW:', pg.inner_text('.wl-preview')[:30], '|', pg.inner_text('.wl h1'), '| link:', pg.get_attribute('.wl-foot a[href^="https://instagram"]', 'href'))
    pg.evaluate("location.hash='welcome'"); pg.wait_for_timeout(1200)
    print('PUBLIC before publish:', pg.inner_text('.wl h1'))
    pg.evaluate("location.hash='admin'"); pg.wait_for_timeout(700); btn(pg, 'انشر')
    pg.wait_for_function("window.__forma.PL.site && window.__forma.PL.site.revision === 1", timeout=30000)
    pg.evaluate("location.hash='welcome'"); pg.wait_for_timeout(1200)
    print('PUBLIC after publish:', pg.inner_text('.wl h1'), '| brand colour:', pg.evaluate("getComputedStyle(document.documentElement).getPropertyValue('--brand')"))
    # maintenance: publish with it on, then a customer sees only the message
    pg.evaluate("location.hash='admin'"); pg.wait_for_timeout(700); pg.check('#cms_maint'); btn(pg, 'انشر')
    pg.wait_for_function("window.__forma.PL.site && window.__forma.PL.site.revision === 2", timeout=30000); pg.wait_for_timeout(300)
    print('admin badge:', pg.locator('#who .pill.warn').all_inner_texts())
    btn(pg, 'تبديل المستخدم'); pg.wait_for_timeout(1000)
    pg.evaluate("location.hash='login'"); pg.wait_for_timeout(300)
    if not pg.locator('#newName').count(): pg.evaluate("location.reload()"); pg.wait_for_timeout(1500)
    if pg.locator('.wl-cta').count() and pg.locator('.wl-cta').is_visible(): pg.locator('.wl-cta').click(); pg.wait_for_timeout(500)
    pg.fill('#newName', 'زبون'); pg.locator('form', has=pg.locator('#newName')).locator('button[type=submit]').click(); pg.wait_for_timeout(1500)
    pg.evaluate("location.hash='new'"); pg.wait_for_timeout(600)
    print('CUSTOMER during maintenance:', pg.inner_text('#v-welcome')[:60].replace('\n', ' '), '| studio visible:', pg.is_visible('#v-studio'))
    # rollback to revision 1 (as admin) — the maintenance screen still lets someone else sign in
    btn(pg, 'تبديل المستخدم'); pg.wait_for_timeout(1500)
    if pg.locator('.wl-cta').count() and pg.locator('.wl-cta').is_visible(): pg.locator('.wl-cta').click(); pg.wait_for_timeout(500)
    pg.locator('button.account', has_text='المدير').click(); pg.wait_for_timeout(1500)
    pg.evaluate("location.hash='admin'"); pg.wait_for_timeout(700)
    pg.locator('summary', has_text='النسخ المنشورة').click(); print('REVISIONS:', pg.locator('summary', has_text='النسخ المنشورة').inner_text())
    pg.locator('button', has_text='استعدها كمسودة').first.click(); pg.wait_for_timeout(900)
    print('draft maintenance after restoring r1:', pg.is_checked('#cms_maint'))
    btn(pg, 'انشر'); pg.wait_for_function("window.__forma.PL.site.revision === 3", timeout=30000)
    print('site revision now:', pg.evaluate("window.__forma.PL.site.revision"), '| maintenance:', pg.evaluate("window.__forma.PL.site.site.maintenance.on"))
    print('artifacts:', S, '| page errors:', errs)
    ctx.close()
