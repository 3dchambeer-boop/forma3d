// OctoPrint client tests against a LOCAL OctoPrint SIMULATOR (node:http).
// The simulator follows the documented REST contract (files/job/printer). It proves
// the client's requests, checks and state interpretation; it is not a real printer.

import assert from 'node:assert/strict';
import { createServer, type IncomingMessage, type Server } from 'node:http';
import type { AddressInfo } from 'node:net';
import { after, before, beforeEach, describe, test } from 'node:test';

import { checkGcode, interpretJob, notReadyReasons, OctoPrintClient, OctoPrintError } from '../../src/lib/printing/octoprint.ts';

interface SimState {
  connected: boolean;
  printing: boolean;
  paused: boolean;
  error: boolean;
  files: Map<string, Buffer>;
  selected: string | null;
  completion: number | null;
  truncateUploads: boolean;
  log: string[];
}

const sim: SimState = { connected: true, printing: false, paused: false, error: false, files: new Map(), selected: null, completion: null, truncateUploads: false, log: [] };
let server: Server;
let base = '';
const KEY = 'octo-test-key';

async function body(req: IncomingMessage): Promise<Buffer> {
  const chunks: Buffer[] = [];
  for await (const c of req) chunks.push(c as Buffer);
  return Buffer.concat(chunks);
}

before(async () => {
  server = createServer(async (req, res) => {
    const json = (code: number, b?: unknown) => {
      res.writeHead(code, { 'Content-Type': 'application/json' });
      res.end(b === undefined ? undefined : JSON.stringify(b));
    };
    if (req.headers['x-api-key'] !== KEY) return json(403, { error: 'Forbidden' });
    const url = req.url ?? '';
    sim.log.push(`${req.method} ${url}`);
    if (url === '/api/version') return json(200, { api: '0.1', server: '1.10.0' });
    if (url === '/api/printer') {
      if (!sim.connected) return json(409, { error: 'Printer is not operational' });
      const text = sim.error ? 'Error' : sim.printing ? 'Printing' : sim.paused ? 'Paused' : 'Operational';
      return json(200, {
        state: { text, flags: { operational: !sim.error, printing: sim.printing, paused: sim.paused, ready: !sim.printing && !sim.paused && !sim.error, error: sim.error, closedOrError: sim.error } },
        temperature: { tool0: { actual: 24.1, target: 0 }, bed: { actual: 23.8, target: 0 } },
      });
    }
    if (url === '/api/files/local' && req.method === 'POST') {
      const raw = await body(req);
      const form = await new Request('http://x/', { method: 'POST', headers: { 'content-type': req.headers['content-type']! }, body: new Uint8Array(raw) }).formData();
      const file = form.get('file') as File;
      let data = Buffer.from(await file.arrayBuffer());
      if (sim.truncateUploads) data = data.subarray(0, data.length - 10);
      sim.files.set(file.name, data);
      if (form.get('print') === 'true') sim.printing = true; // must never happen from our client
      return json(201, { done: true, files: { local: { name: file.name, path: file.name, origin: 'local' } } });
    }
    const fileMatch = url.match(/^\/api\/files\/local\/(.+)$/);
    if (fileMatch) {
      const name = decodeURIComponent(fileMatch[1]);
      if (!sim.files.has(name)) return json(404, { error: 'not found' });
      if (req.method === 'GET') return json(200, { name, path: name, size: sim.files.get(name)!.length });
      const cmd = JSON.parse((await body(req)).toString());
      if (cmd.command === 'select') {
        if (sim.printing) return json(409);
        sim.selected = name;
        return json(204);
      }
    }
    if (url === '/api/job' && req.method === 'GET') {
      const state = sim.error ? 'Error' : sim.printing ? 'Printing' : sim.paused ? 'Paused' : 'Operational';
      return json(200, { job: { file: { name: sim.selected, path: sim.selected } }, progress: { completion: sim.completion, printTime: 10, printTimeLeft: 50 }, state });
    }
    if (url === '/api/job' && req.method === 'POST') {
      const cmd = JSON.parse((await body(req)).toString());
      if (cmd.command === 'start') {
        if (!sim.connected || sim.printing || !sim.selected) return json(409);
        sim.printing = true;
        sim.completion = 0;
        return json(204);
      }
      if (cmd.command === 'cancel') {
        if (!sim.printing && !sim.paused) return json(409);
        sim.printing = false;
        sim.paused = false;
        return json(204);
      }
    }
    json(404, { error: 'unknown' });
  });
  await new Promise<void>((r) => server.listen(0, '127.0.0.1', r));
  base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
});

after(() => server.close());

beforeEach(() => {
  Object.assign(sim, { connected: true, printing: false, paused: false, error: false, selected: null, completion: null, truncateUploads: false, log: [] });
  sim.files.clear();
});

const GCODE = Buffer.from('; generated by OrcaSlicer\nM140 S60\nM104 S210\nG28\nG1 X10 Y10 Z0.2 F3000\nG1 X20 E1.2\nM104 S0\n');

describe('OctoPrint client', () => {
  test('wrong key is reported as AUTH, not as a printer problem', async () => {
    const c = new OctoPrintClient(base, 'wrong');
    await assert.rejects(c.version(), (e: OctoPrintError) => e.code === 'AUTH');
  });

  test('upload never starts a print, and verifies the stored size', async () => {
    const c = new OctoPrintClient(base, KEY);
    const { path } = await c.upload(GCODE, 'job-123.gcode');
    assert.equal(path, 'job-123.gcode');
    assert.equal(sim.printing, false);
    assert.ok(sim.log.includes('GET /api/files/local/job-123.gcode'), 'upload verified with a file-info request');
  });

  test('truncated upload is detected', async () => {
    sim.truncateUploads = true;
    const c = new OctoPrintClient(base, KEY);
    await assert.rejects(c.upload(GCODE, 'job-1.gcode'), (e: OctoPrintError) => e.code === 'UPLOAD_MISMATCH');
  });

  test('unsafe filenames are refused before any request', async () => {
    const c = new OctoPrintClient(base, KEY);
    await assert.rejects(c.upload(GCODE, '../../etc/x.gcode'));
    assert.equal(sim.log.length, 0);
  });

  test('readiness: disconnected, busy and error printers are not ready', async () => {
    const c = new OctoPrintClient(base, KEY);
    assert.deepEqual(notReadyReasons(await c.printer()), []);
    sim.connected = false;
    assert.match(notReadyReasons(await c.printer())[0], /not connected/);
    sim.connected = true;
    sim.printing = true;
    assert.ok(notReadyReasons(await c.printer()).some((r) => r.includes('busy')));
    sim.printing = false;
    sim.error = true;
    assert.ok(notReadyReasons(await c.printer()).some((r) => r.includes('error')));
  });

  test('full cycle: upload → select → start → progress → completion is read from the printer', async () => {
    const c = new OctoPrintClient(base, KEY);
    const { path } = await c.upload(GCODE, 'job-9.gcode');
    await c.select(path);
    await c.start();
    sim.completion = 42.5;
    let r = interpretJob(await c.job(), path, false);
    assert.deepEqual([r.status, r.progress], ['PRINTING', 42.5]);
    sim.printing = false;
    sim.completion = 100;
    r = interpretJob(await c.job(), path, false);
    assert.equal(r.status, 'COMPLETED');
  });

  test('start while already printing is a CONFLICT', async () => {
    const c = new OctoPrintClient(base, KEY);
    const { path } = await c.upload(GCODE, 'a.gcode');
    await c.select(path);
    await c.start();
    await assert.rejects(c.start(), (e: OctoPrintError) => e.code === 'CONFLICT');
  });

  test('unreachable OctoPrint is UNREACHABLE', async () => {
    const c = new OctoPrintClient('http://127.0.0.1:1', KEY, 2000);
    await assert.rejects(c.version(), (e: OctoPrintError) => e.code === 'UNREACHABLE');
  });

  test('API key comes from the env var named on the printer, never from the row', () => {
    process.env.OCTOPRINT_KEY_TEST1 = KEY;
    assert.ok(OctoPrintClient.forPrinter({ octoprintUrl: base, octoprintApiKeyRef: 'OCTOPRINT_KEY_TEST1' }));
    assert.throws(() => OctoPrintClient.forPrinter({ octoprintUrl: base, octoprintApiKeyRef: 'MISSING_VAR_X' }), /not set/);
    assert.throws(() => OctoPrintClient.forPrinter({ octoprintUrl: base, octoprintApiKeyRef: 'lowercase; rm -rf' }), /reference/);
  });
});

describe('job interpretation', () => {
  const base = { fileName: 'f.gcode', filePath: 'f.gcode', printTime: 1, printTimeLeft: 1, error: null };
  test('idle below 100 % without a cancel is UNKNOWN, never COMPLETED', () => {
    assert.equal(interpretJob({ ...base, state: 'Operational', completion: 63 }, 'f.gcode', false).status, 'UNKNOWN');
    assert.equal(interpretJob({ ...base, state: 'Operational', completion: 63 }, 'f.gcode', true).status, 'CANCELLED');
  });
  test('errors and other files', () => {
    assert.equal(interpretJob({ ...base, state: 'Offline after error', completion: 10, error: 'Thermal runaway' }, 'f.gcode', false).status, 'FAILED');
    assert.equal(interpretJob({ ...base, state: 'Printing', completion: 10 }, 'other.gcode', false).status, 'UNKNOWN');
  });
});

describe('G-code sanity check', () => {
  test('accepts real-looking G-code and rejects empty or motionless files', () => {
    assert.deepEqual(checkGcode(GCODE), []);
    assert.deepEqual(checkGcode(Buffer.alloc(0)), ['G-code file is empty']);
    assert.ok(checkGcode(Buffer.from('; only comments\n')).includes('no G0/G1 motion commands'));
  });
});
