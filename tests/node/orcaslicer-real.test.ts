// REAL OrcaSlicer CLI (no simulator): slices meshes from the CAD kernel with the flattened Ender-3 presets.
// Runs when ORCASLICER_BIN and ORCASLICER_PROFILE_DIR are set (scripts/orcaslicer-headless-setup.sh).
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, test } from 'node:test';

import { OrcaSlicerError, runOrcaSlicer } from '../../src/lib/orcaslicer.ts';
import { checkGcode } from '../../src/lib/printing/octoprint.ts';

const require = createRequire(import.meta.url);
const CAD = require(join(resolve(import.meta.dirname, '../..'), 'services/ai_3d_engine/browser/cad.js'));
const enabled = !!(process.env.ORCASLICER_BIN && process.env.ORCASLICER_PROFILE_DIR);
const PRESETS = JSON.stringify({ machine: 'machine.json', process: 'process.json', filament: 'filament-creality-generic-pla.json' });
const dir = mkdtempSync(join(tmpdir(), 'orca-real-'));
async function stlOf(model: unknown, name: string) {
  const r = await CAD.generateDesign({ model });
  const p = join(dir, name + '.stl');
  writeFileSync(p, Buffer.from(r.stl));
  return { path: p, size: r.size_mm };
}

describe('OrcaSlicer (real binary)', { skip: !enabled && 'ORCASLICER_BIN / ORCASLICER_PROFILE_DIR not set' }, () => {
  test('a 20 mm cube slices into 100 layers of 0.2 mm with a sane print estimate', async () => {
    const { path } = await stlOf({ box: { size: [20, 20, 20] } }, 'cube');
    const r = await runOrcaSlicer({ modelPath: path, profileConfigJson: PRESETS });
    const g = r.gcode.toString('utf8');
    assert.match(g, /generated by OrcaSlicer 2\./);
    assert.match(g, /; max_z_height: 20\.00/);
    assert.equal(r.layerCount, 100);
    assert.ok(r.printTimeSec! > 600 && r.printTimeSec! < 3 * 3600, String(r.printTimeSec));
    assert.ok(r.filamentLengthMm! > 500 && r.filamentLengthMm! < 10000, String(r.filamentLengthMm));
    // the PLA preset's temperatures reach the G-code
    assert.match(g, /M104 S2\d\d|M109 S2\d\d/);
    assert.deepEqual(checkGcode(r.gcode), []);
  });

  test('a designed part (headphone hook starter) slices; G-code height equals the part height', async () => {
    const { STARTERS } = require(join(resolve(import.meta.dirname, '../..'), 'services/ai_3d_engine/browser/starters.js'));
    const st = STARTERS.find((s: any) => s.key === 'hex_wrench');
    const res = await CAD.generateDesign(st.design);
    const p = join(dir, 'wrench.stl'); writeFileSync(p, Buffer.from(res.stl));
    const r = await runOrcaSlicer({ modelPath: p, profileConfigJson: PRESETS });
    const zmax = Number(/; max_z_height: ([\d.]+)/.exec(r.gcode.toString('utf8'))![1]);
    assert.ok(Math.abs(zmax - res.size_mm.z) < 0.21, `${zmax} vs ${res.size_mm.z}`);
  });

  test('a part larger than the 220 x 220 bed is refused by the slicer, not silently printed', async () => {
    const { path } = await stlOf({ box: { size: [300, 40, 10] } }, 'huge');
    await assert.rejects(runOrcaSlicer({ modelPath: path, profileConfigJson: PRESETS }), (e: unknown) => e instanceof OrcaSlicerError && e.code === 'EXECUTION_FAILED');
  });
});
